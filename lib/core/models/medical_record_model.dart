import 'package:json_annotation/json_annotation.dart';

part 'medical_record_model.g.dart';

@JsonSerializable()
class MedicalRecordModel {
  final String id;

  @JsonKey(name: 'appointment_id')
  final String appointmentId;

  final String diagnosis;
  final String? treatment;
  final String? vaccination;

  @JsonKey(
    name: 'next_visit',
    toJson: _dateToJson,
  )
  final DateTime? nextVisit;

  @JsonKey(name: 'created_at')
  final DateTime createdAt;

  const MedicalRecordModel({
    required this.id,
    required this.appointmentId,
    required this.diagnosis,
    this.treatment,
    this.vaccination,
    this.nextVisit,
    required this.createdAt,
  });

  factory MedicalRecordModel.fromMap(Map<String, dynamic> json) =>
      _$MedicalRecordModelFromJson(json);

  Map<String, dynamic> toMap() => _$MedicalRecordModelToJson(this);

  // Exclude fields generated by Supabase when inserting.
  Map<String, dynamic> toInsertJson() {
    return toMap()
      ..remove('id')
      ..remove('created_at');
  }

  // PostgreSQL date: YYYY-MM-DD, without time or timezone.
  static String? _dateToJson(DateTime? value) {
    if (value == null) return null;

    final year = value.year.toString().padLeft(4, '0');
    final month = value.month.toString().padLeft(2, '0');
    final day = value.day.toString().padLeft(2, '0');

    return '$year-$month-$day';
  }
}